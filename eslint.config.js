// Vendora ESLint flat config (ESLint 10) — Vite + React 19 + TypeScript.
//
// Layers:
//   1. @eslint/js recommended          — core JS correctness rules
//   2. typescript-eslint recommended   — TS correctness rules (non-type-checked set;
//                                        type-aware linting is intentionally not enabled:
//                                        `npm run typecheck` / the build already run tsc -b,
//                                        and type-aware lint on 330+ files is too slow for a gate)
//   3. react-hooks flat recommended    — with per-rule tuning notes below
//   4. react-refresh                   — Vite HMR export hygiene (warn)
//
// Rule tuning notes (kept deliberately small and explicit):
//   - react-hooks v7 ships the React Compiler rule family (immutability, refs,
//     set-state-in-effect, static-components, preserve-manual-memoization,
//     use-memo, globals, error-boundaries) as ERRORS in its recommended set.
//     This codebase predates those rules; several hundred findings are legacy
//     patterns, not bugs, and mass-fixing them in a quality-gates batch would
//     risk behaviour changes. They are therefore set to "warn" so every
//     finding stays visible and new code is still flagged, with a burn-down
//     path to errors. `rules-of-hooks` stays an error and `exhaustive-deps`
//     stays a warning, exactly as the recommended set defines them.
//   - `@typescript-eslint/no-unused-vars` mirrors tsconfig's
//     noUnusedLocals/noUnusedParameters; `_`-prefixed args/vars are the
//     codebase convention for intentionally-unused bindings.
//   - `@typescript-eslint/no-explicit-any` is "warn", not the recommended
//     "error": the tree carries 84 legacy `any`s (concentrated in scripts/
//     and the e2e harness). They are all reported on every run; burn them
//     down file-by-file and promote this back to "error" at zero.
//   - `src/types/database.ts` is generated by `supabase gen types`; its
//     no-arg RPCs are typed `Args: {}` by the generator. The
//     no-empty-object-type rule is scoped off for that file only rather
//     than hand-editing generated output.
